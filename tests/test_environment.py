def _run_pytest(tmp_path, probe, *extra):
    cmd = [sys.executable, "-m", "pytest", "-c", str(ROOT / "pyproject.toml"), "--rootdir", str(tmp_path),
           str(probe), "-q", "-p", "no:cacheprovider", *extra]
    return subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")


def test_unknown_marker_aborts_and_deselection_works(tmp_path):
    probe = tmp_path / "test_probe.py"
    probe.write_text("import pytest\n\n\n@pytest.mark.typo\ndef test_typo():\n    pass\n", encoding="utf-8")
    res = _run_pytest(tmp_path, probe)
    assert res.returncode != 0
    assert "not found in `markers` configuration option" in res.stdout + res.stderr

    probe2 = tmp_path / "test_probe2.py"
    probe2.write_text("import pytest\n\n\n@pytest.mark.data\ndef test_needs_data():\n    assert False\n\n\n"
                      "def test_plain():\n    pass\n", encoding="utf-8")
    res = _run_pytest(tmp_path, probe2, "-m", "not data and not slow")
    assert res.returncode == 0, res.stdout + res.stderr
    assert "1 deselected" in res.stdout
