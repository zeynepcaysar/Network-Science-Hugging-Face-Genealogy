"""Guards for the pinned environment (ENV-02) and the pytest configuration (ENV-04).

Checks that the venv is the uv-managed Python 3.13, that every package matches constraints.txt, that the
stack imports, that powerlaw recovers a known exponent, and that pyproject.toml carries the pytest markers.

Run from the repo root after activating the venv:  python -m pytest tests/test_environment.py
"""
import importlib.metadata as md
import re
import subprocess
import sys
import tomllib
import warnings
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
COMPILE_CMD = "uv pip compile --universal --python-version 3.13 requirements.txt -o constraints.txt"
DIRECT = ["pandas", "powerlaw", "numpy", "scipy", "networkx", "pyarrow", "matplotlib", "huggingface-hub", "pytest",
          "hypothesis"]


def _text(name):
    return (ROOT / name).read_text(encoding="utf-8")


def _pins():
    """Return {canonical name: version} for every pin in constraints.txt that applies to this platform."""
    pins = {}
    for line in _text("constraints.txt").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        req = Requirement(line.split("#", 1)[0].strip())
        if req.marker is not None and not req.marker.evaluate():
            continue
        (spec,) = list(req.specifier)
        assert spec.operator == "==", line
        pins[canonicalize_name(req.name)] = spec.version
    return pins


def test_python_is_uv_managed_313():
    assert sys.version_info[:2] == (3, 13), sys.version
    assert "WindowsApps" not in sys.base_prefix and "PythonSoftwareFoundation" not in sys.base_prefix, sys.base_prefix


def test_installed_matches_constraints():
    pins = _pins()
    assert len(pins) >= 10
    for name in DIRECT:
        assert canonicalize_name(name) in pins, name
    drift = {n: (v, md.version(n)) for n, v in pins.items() if md.version(n) != v}
    assert not drift, f"installed != pinned (pinned, installed): {drift}"


def test_direct_pins_match_env02():
    want = {"pandas": "3.1.1", "powerlaw": "2.0.0", "numpy": "2.5.5", "scipy": "1.18.1", "networkx": "3.7",
            "pyarrow": "26.0.1", "pytest": "9.2.0", "hypothesis": "6.170.17"}
    assert {n: md.version(n) for n in want} == want


