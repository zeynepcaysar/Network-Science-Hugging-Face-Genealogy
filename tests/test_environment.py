def test_powerlaw_smoke_fit():
    import numpy as np
    import powerlaw
    x = np.random.default_rng(12345).zipf(2.5, size=20000)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        fit = powerlaw.Fit(x, discrete=True, verbose=False)
        alpha, xmin = fit.power_law.alpha, fit.xmin
    assert abs(alpha - 2.5) < 0.1 and xmin >= 1


def test_requirements_are_floors():
    lines = [l.strip() for l in _text("requirements.txt").splitlines() if l.strip()]
    assert all(re.fullmatch(r"[A-Za-z0-9_.-]+", l) for l in lines), lines
    want = {"huggingface_hub", "networkx", "pandas", "numpy", "scipy", "matplotlib", "powerlaw", "pyarrow", "pytest",
            "hypothesis"}
    assert want <= set(lines)


